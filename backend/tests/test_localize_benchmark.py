"""The localization benchmark, run against the bundled toy pair.

`test_localize.py` unit-tests the pieces on synthetic arrays. This file asks the
only question that finally matters: on a dataset with exact ground truth and
populations designed to defeat it, does the method work, and do the two
confidence scores tell the truth about when it doesn't?

The toy pair is generated by ``xcell.data.generate_toy_localize``. Four
region-restricted populations are localizable; ``Immune`` (dispersed),
``Bipolar`` (two distant patches, one program) and ``Circulating`` (query-only)
are each unlocalizable for a different reason.
"""
from pathlib import Path

import anndata
import numpy as np
import pytest

from xcell.localize import (
    cross_validate_localization,
    evaluate_localization,
    project_knn,
)

DATA = Path(__file__).resolve().parents[1] / 'xcell' / 'data'
LOCALIZABLE = ('Apical', 'Basal', 'Anterior', 'Posterior')
BIPOLAR_PATCHES = np.array([[45.0, 30.0], [160.0, 135.0]])


def _pair():
    ref = anndata.read_h5ad(DATA / 'toy_localize_spatial.h5ad')
    query = anndata.read_h5ad(DATA / 'toy_localize_scrna.h5ad')
    return (
        np.asarray(query.X.todense()),
        np.asarray(ref.X.todense()),
        np.asarray(ref.obsm['spatial'], dtype=float),
        np.asarray(query.obsm['spatial_true'], dtype=float),
        query.obs['cell_type'].astype(str).values,
    )


@pytest.fixture(scope='module')
def pair():
    return _pair()


@pytest.fixture(scope='module')
def projection(pair):
    q_expr, ref_expr, ref_coords, _, _ = pair
    return project_knn(q_expr, ref_expr, ref_coords, k=20)


def _median_error(coords, truth, mask=None):
    if mask is not None:
        coords, truth = coords[mask], truth[mask]
    ok = np.isfinite(coords).all(axis=1)
    return float(np.median(np.linalg.norm(coords[ok] - truth[ok], axis=1)))


# --- the datasets themselves ---------------------------------------------

def test_the_toy_pair_ships_with_the_package():
    assert (DATA / 'toy_localize_spatial.h5ad').exists()
    assert (DATA / 'toy_localize_scrna.h5ad').exists()


def test_the_query_carries_its_own_answer_key():
    query = anndata.read_h5ad(DATA / 'toy_localize_scrna.h5ad')
    assert 'spatial_true' in query.obsm
    # ...but not under a key that would make anything treat it as spatial input.
    assert 'spatial' not in query.obsm and 'X_spatial' not in query.obsm


def test_both_files_share_a_gene_panel():
    ref = anndata.read_h5ad(DATA / 'toy_localize_spatial.h5ad')
    query = anndata.read_h5ad(DATA / 'toy_localize_scrna.h5ad')
    assert list(ref.var_names) == list(query.var_names)


def test_the_query_holds_every_population_the_benchmark_needs():
    query = anndata.read_h5ad(DATA / 'toy_localize_scrna.h5ad')
    types = set(query.obs['cell_type'].astype(str))
    assert types >= {*LOCALIZABLE, 'Immune', 'Bipolar', 'Circulating'}


# --- does it work --------------------------------------------------------

def test_it_beats_both_baselines(pair, projection):
    _, _, ref_coords, truth, groups = pair
    m = evaluate_localization(projection.coords, truth, ref_coords=ref_coords,
                              confidence=projection.confidence, groups=groups)
    assert m['median_error'] < m['baseline_centroid'] / 1.5
    assert m['median_error'] < m['baseline_random'] / 2


def test_the_localizable_populations_are_localized(pair, projection):
    """Under a tenth of the tissue diameter for the four regional programs."""
    _, _, _, truth, groups = pair
    diameter = float(np.linalg.norm(truth.max(axis=0) - truth.min(axis=0)))
    for label in LOCALIZABLE:
        err = _median_error(projection.coords, truth, groups == label)
        assert err < 0.12 * diameter, f'{label}: {err:.1f}'


def test_global_structure_is_preserved(pair, projection):
    _, _, ref_coords, truth, _ = pair
    m = evaluate_localization(projection.coords, truth, ref_coords=ref_coords)
    assert m['structure_correlation'] > 0.2


# --- and does it admit when it doesn't -----------------------------------

def test_the_unlocalizable_populations_really_are_placed_badly(pair, projection):
    """The premise the confidence score exists to flag. If these were placed
    well there would be nothing to warn about."""
    _, _, _, truth, groups = pair
    good = np.mean([_median_error(projection.coords, truth, groups == g)
                    for g in LOCALIZABLE])
    for label in ('Immune', 'Bipolar'):
        assert _median_error(projection.coords, truth, groups == label) > 2 * good


def test_confidence_separates_localizable_from_dispersed(pair, projection):
    _, _, _, _, groups = pair
    localizable = np.isin(groups, LOCALIZABLE)
    assert projection.confidence[localizable].mean() > 0.5
    assert projection.confidence[groups == 'Immune'].mean() < 0.2
    assert projection.confidence[groups == 'Bipolar'].mean() < 0.2


def test_confidence_predicts_error(pair, projection):
    """The design's falsification test: a score that does not predict error is
    decoration."""
    _, _, ref_coords, truth, _ = pair
    m = evaluate_localization(projection.coords, truth, ref_coords=ref_coords,
                              confidence=projection.confidence)
    assert m['confidence_error_correlation'] < -0.4


def test_a_query_only_population_is_caught_by_similarity_not_confidence(pair, projection):
    """`Circulating` has no counterpart in the reference. Its neighbours may
    still agree on a location — the point is that it resembles none of them."""
    _, _, _, _, groups = pair
    known = np.isin(groups, LOCALIZABLE)
    assert (projection.similarity[groups == 'Circulating'].mean()
            < projection.similarity[known].mean() - 0.15)


# --- the score is actionable, not just descriptive -----------------------

def test_filtering_on_confidence_improves_the_map(pair):
    q_expr, ref_expr, ref_coords, truth, _ = pair
    loose = project_knn(q_expr, ref_expr, ref_coords, k=20)
    strict = project_knn(q_expr, ref_expr, ref_coords, k=20, min_confidence=0.2)
    assert (_median_error(strict.coords, truth)
            < _median_error(loose.coords, truth) * 0.8)


def test_the_threshold_keeps_roughly_the_localizable_cells(pair):
    """Not a coincidence worth hiding: the cells it drops are the ones the
    benchmark was built to make undroppable by any other means."""
    q_expr, ref_expr, ref_coords, _, groups = pair
    p = project_knn(q_expr, ref_expr, ref_coords, k=20, min_confidence=0.2)
    kept = np.isfinite(p.coords).all(axis=1)
    localizable = np.isin(groups, LOCALIZABLE)
    # Almost every regional cell survives; almost every dispersed one does not.
    assert kept[localizable].mean() > 0.9
    assert kept[groups == 'Immune'].mean() < 0.2


# --- aggregation on the bimodal population -------------------------------

def _distance_to_a_patch(coords):
    return np.min(
        np.linalg.norm(coords[:, None, :] - BIPOLAR_PATCHES[None, :, :], axis=2),
        axis=1,
    )


def test_the_mean_puts_bimodal_cells_in_the_empty_gap(pair):
    q_expr, ref_expr, ref_coords, _, groups = pair
    p = project_knn(q_expr, ref_expr, ref_coords, k=20, aggregation='weighted_mean')
    assert np.median(_distance_to_a_patch(p.coords[groups == 'Bipolar'])) > 30


def test_densest_puts_them_in_real_tissue_instead(pair):
    """The precise claim, and the limit of it: `densest` lands the cell in one
    of the two patches rather than in the gap between them. It cannot say
    *which* patch — the two are transcriptionally identical, so nothing can —
    which is why these cells still score near-zero confidence."""
    q_expr, ref_expr, ref_coords, _, groups = pair
    p = project_knn(q_expr, ref_expr, ref_coords, k=20, aggregation='densest')
    bipolar = groups == 'Bipolar'
    assert np.median(_distance_to_a_patch(p.coords[bipolar])) < 15
    assert p.confidence[bipolar].mean() < 0.2


def test_no_aggregation_is_worse_than_the_centroid_baseline(pair):
    q_expr, ref_expr, ref_coords, truth, _ = pair
    baseline = float(np.median(
        np.linalg.norm(truth - ref_coords.mean(axis=0), axis=1)
    ))
    for aggregation in ('weighted_mean', 'median', 'best_match', 'densest'):
        p = project_knn(q_expr, ref_expr, ref_coords, k=20, aggregation=aggregation)
        assert _median_error(p.coords, truth) < baseline, aggregation


# --- transforms on real cross-platform data ------------------------------

def test_a_per_dataset_transform_beats_none_across_platforms(pair):
    """The two files differ in depth, dropout and per-gene capture — which is
    the whole reason the default is not `none`."""
    q_expr, ref_expr, ref_coords, truth, _ = pair
    raw = project_knn(q_expr, ref_expr, ref_coords, k=20, transform='none')
    zsc = project_knn(q_expr, ref_expr, ref_coords, k=20, transform='zscore')
    assert _median_error(zsc.coords, truth) < _median_error(raw.coords, truth)


# --- cross-validation as a stand-in when truth is unknown ----------------

def test_cross_validating_the_reference_predicts_the_real_ranking(pair):
    """What a user actually does: they have no ground truth for their query, so
    they hold out part of the reference instead. That number is optimistic — no
    platform gap to cross — but it must at least be in the right territory."""
    _, ref_expr, ref_coords, _, _ = pair
    cv = cross_validate_localization(ref_expr, ref_coords, k=20, holdout_fraction=0.2)
    assert cv['same_platform'] is True
    assert cv['median_error'] < cv['baseline_centroid'] / 1.5
